-- Portable between PostgreSQL and H2 (MODE=PostgreSQL) so tests run against the same schema as production.

create table syllabi (
    id                bigint generated by default as identity primary key,
    title             varchar(200)  not null,
    faculty           varchar(120)  not null,
    department        varchar(120)  not null,
    semester          varchar(40)   not null,
    original_filename varchar(255)  not null,
    sha256            varchar(64)   not null,
    uploaded_by       varchar(64)   not null,
    uploaded_at       timestamp with time zone not null
);
create index idx_syllabi_uploaded_by on syllabi (uploaded_by);
create index idx_syllabi_catalogue on syllabi (faculty, department, semester);

create table syllabus_topics (
    syllabus_id bigint       not null references syllabi (id) on delete cascade,
    position    integer      not null,
    topic       varchar(200) not null,
    primary key (syllabus_id, position)
);

create table study_plans (
    id            bigint generated by default as identity primary key,
    syllabus_id   bigint      not null references syllabi (id),
    user_id       varchar(64) not null,
    start_date    date        not null,
    end_date      date        not null,
    hours_per_day integer     not null,
    created_at    timestamp with time zone not null,
    updated_at    timestamp with time zone not null,
    version       bigint      not null default 0,
    constraint ck_plan_dates check (end_date >= start_date)
);
create index idx_study_plans_user on study_plans (user_id);

create table study_sessions (
    id            bigint generated by default as identity primary key,
    study_plan_id bigint       not null references study_plans (id) on delete cascade,
    topic         varchar(200) not null,
    start_time    timestamp    not null,
    end_time      timestamp    not null,
    completed     boolean      not null default false,
    completed_at  timestamp with time zone,
    constraint ck_session_window check (end_time > start_time)
);
create index idx_study_sessions_plan on study_sessions (study_plan_id);

-- Append-only: the application maps this table as immutable and never issues UPDATE or DELETE.
create table audit_events (
    id          bigint generated by default as identity primary key,
    occurred_at timestamp with time zone not null,
    actor       varchar(64)  not null,
    action      varchar(64)  not null,
    entity_type varchar(64)  not null,
    entity_id   varchar(64)  not null,
    request_id  varchar(64),
    details     varchar(1000)
);
create index idx_audit_actor on audit_events (actor, occurred_at);

create table idempotency_records (
    idempotency_key varchar(100) not null,
    scope           varchar(100) not null,
    request_hash    varchar(64)  not null,
    response_status integer      not null,
    response_body   varchar(1000000) not null,
    created_at      timestamp with time zone not null,
    primary key (scope, idempotency_key)
);
